#!/usr/bin/env node
/**
 * P#48 — model metadata snapshot sync (Maka refresh:model-metadata parity).
 *
 *   1. Offline (default): regenerate cli/src/model-metadata.ts from the
 *      committed snapshot scripts/model-metadata.snapshot.json. No network.
 *   2. --fetch: download https://models.dev/api.json, merge into the
 *      snapshot. FAILS CLOSED when any existing snapshot entry would lose a
 *      field; pass --accept-upstream-removals to acknowledge explicitly.
 *
 * The generated .ts is derived data — edit the snapshot instead.
 */
import { readFileSync, writeFileSync } from "node:fs";

const args = new Set(process.argv.slice(2));
const doFetch = args.has("--fetch");
const acceptRemovals = args.has("--accept-upstream-removals");
const SNAPSHOT = "scripts/model-metadata.snapshot.json";
const GENERATED = "cli/src/model-metadata.ts";

function loadSnapshot() {
  try {
    return JSON.parse(readFileSync(SNAPSHOT, "utf8"));
  } catch {
    return {};
  }
}

async function fetchLive() {
  const res = await fetch("https://models.dev/api.json");
  if (!res.ok) throw new Error(`models.dev fetch failed: HTTP ${res.status}`);
  return res.json();
}

function extractPrices(m) {
  const p = m?.cost ?? m?.price;
  if (!p || typeof p.input !== "number" || typeof p.output !== "number") return undefined;
  return { input: p.input, output: p.output };
}

function extractContextWindow(m) {
  const lw = m?.limit?.context ?? m?.context_window ?? m?.contextWindow;
  return typeof lw === "number" && lw > 0 ? Math.floor(lw) : undefined;
}

async function main() {
  let snapshot = loadSnapshot();

  if (doFetch) {
    const catalog = await fetchLive();
    const removals = [];
    for (const [providerId, provider] of Object.entries(catalog)) {
      const models = provider?.models ?? {};
      for (const [modelId, meta] of Object.entries(models)) {
        const key = `${providerId}/${modelId}`;
        const prices = extractPrices(meta);
        const contextWindow = extractContextWindow(meta);
        if (!prices && !contextWindow) continue;
        const prev = snapshot[key];
        const next = {
          ...(prev ?? {}),
          ...(prices ? { price: prices } : {}),
          ...(contextWindow ? { contextWindow } : {}),
        };
        if (prev) {
          if (prev.price && !next.price) removals.push(`${key}: price dropped`);
          if (prev.contextWindow && !next.contextWindow) removals.push(`${key}: contextWindow dropped`);
        }
        snapshot[key] = next;
      }
    }
    if (removals.length > 0 && !acceptRemovals) {
      console.error("FAIL: upstream metadata dropped existing fields:");
      for (const r of removals) console.error(`  - ${r}`);
      console.error("Review intentionally, then rerun with --accept-upstream-removals.");
      process.exit(1);
    }
    writeFileSync(SNAPSHOT, JSON.stringify(snapshot, null, 2) + "\n");
    console.log(`snapshot updated (${Object.keys(snapshot).length} entries)`);
  }

  const entries = Object.entries(loadSnapshot());
  const lines = [
    "// GENERATED by scripts/model-metadata.mjs — do not edit by hand.",
    "// Source: scripts/model-metadata.snapshot.json (refreshed from models.dev).",
    "",
    'import type { ModelPrice } from "./cost.js";',
    "",
    "export interface ModelMeta {",
    "  /** $ / 1M input+output tokens */",
    "  price?: ModelPrice;",
    "  /** maximum context window in tokens */",
    "  contextWindow?: number;",
    "}",
    "",
    "/** Committed metadata snapshot — merged under user `prices` overrides. */",
    "export const MODEL_METADATA: Record<string, ModelMeta> = {",
  ];
  for (const [key, meta] of entries.sort(([a], [b]) => a.localeCompare(b))) {
    const parts = [];
    if (meta.price) parts.push(`price: { input: ${meta.price.input}, output: ${meta.price.output} }`);
    if (meta.contextWindow) parts.push(`contextWindow: ${meta.contextWindow}`);
    lines.push(`  ${JSON.stringify(key)}: { ${parts.join(", ")} },`);
  }
  lines.push("};", "");
  writeFileSync(GENERATED, lines.join("\n"));
  console.log(`generated ${GENERATED} from ${entries.length} snapshot entries`);
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : String(err));
  process.exit(1);
});
